import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
const wifi=readFileSync('firmware/dloop_wifi_scale/wifi_transport.h','utf8');
const start=wifi.indexOf('  if(!client.connected()){');
const end=wifi.indexOf('  nextUpload=now+1000;char body[768];',start);
assert(start>0&&end>start);
const warmup=wifi.slice(start,end);
assert(warmup.includes('queued[0]=0;'));
assert(warmup.includes('client.connect(host,443)'));
assert(warmup.includes('client.requireEstablished(true);'));
assert(warmup.includes('return; // Even a successful handshake'));
assert(!warmup.includes('http.POST(')&&!warmup.includes('sentAt=')&&!warmup.includes('wallMs()'));
assert(wifi.indexOf('uint32_t(now-queuedAt)>500')<start);
assert(wifi.includes('queuedAt=millis();sentAt=wallMs();'));
assert(wifi.includes('httpResponseMs=postMs;'));
const tls=readFileSync('firmware/dloop_wifi_scale/tls_checked_client.h','utf8');
assert(tls.includes('if(establishedOnly)return connected()?1:0;'));
assert(tls.indexOf('if(establishedOnly)')<tls.indexOf('BearSSL::WiFiClientSecure::connect(host,port)'));
assert(tls.includes('new CheckedScaleTlsClient(*this)'));
const core=readFileSync('firmware/dloop_usb_scale/dloop_usb_scale.ino','utf8');
assert(core.indexOf('sensor.read()')<core.indexOf('wifiScale.tick('));
const php=process.env.DLOOP_PHP_BINARY||'.tools/php/php.exe';
const result=spawnSync(php,['backend/tests/wifi-upload-clock-offline.php'],{encoding:'utf8'});
assert.equal(result.status,0,result.stderr||result.stdout);
process.stdout.write(result.stdout);
console.log('PASS: verified TLS warmup discards old frame and returns to acquisition; POST clone cannot re-handshake; capture timestamp and 500 ms expiry preserved.');
