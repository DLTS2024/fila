assert.equal(formatPreviewWeight(-1000),'-1.000 kg');
assert.equal(formatPreviewWeight(null),'— g');
assert.equal(formatPreviewWeight(NaN),'— g');
assert.equal(UNVERIFIED_COUNTS_PER_GRAM,213.656);
assert(Math.abs(unverifiedEstimatedGrams(385008,true,true)-1801.9994757928632)<.000001);
assert.equal(unverifiedEstimatedGrams(0,true,true),0);
