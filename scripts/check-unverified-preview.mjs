import assert from 'node:assert/strict';
import fs from 'node:fs';
import './test-typescript-loader.mjs';
const {UNVERIFIED_COUNTS_PER_GRAM,unverifiedEstimatedGrams}=await import('../lib/scale/unverified-preview.ts');
const {parseScaleFrame}=await import('../lib/scale/protocol.ts');
const {DISPLAY_ZERO_DEADBAND_G,formatPreviewWeight}=await import('../lib/scale/weight-display.ts');
