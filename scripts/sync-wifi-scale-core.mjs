import {readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';

// Arduino IDE builds a relocated sketch. Bundle only the nonsecret USB core;
// transport/private configuration remain normal local Wi-Fi sketch headers.
const root = path.resolve('firmware/dloop_usb_scale');
const seen = new Set();
function expand(file) {
  const absolute = path.resolve(root, file);
  assert(absolute.startsWith(root + path.sep));
  if (seen.has(absolute)) return '';
  seen.add(absolute);
  const source = readFileSync(absolute, 'utf8').replaceAll('\r\n', '\n');
  return `// BEGIN ${file}\n` + source
    .replace(/^#pragma once\s*$/gm, '')
    .replace(/^#include "([^"]+)"[^\n]*$/gm, (line, name) => {
      if (name === '../dloop_wifi_scale/wifi_transport.h' || name === '../dloop_wifi_scale/single_point_calibration.h') return '#include "'+path.basename(name)+'"';
      return expand(name);
    }) + `\n// END ${file}\n`;
}
const content = '// Generated by node scripts/sync-wifi-scale-core.mjs; do not edit.\n'
  + '// Regenerate after USB core/header changes. No credentials are bundled.\n'
  + '#pragma once\n' + expand('dloop_usb_scale.ino');
const output = 'firmware/dloop_wifi_scale/scale_core.generated.h';
if (process.argv.slice(2).includes('--check')) {
  assert.equal(readFileSync(output, 'utf8').replaceAll('\r\n', '\n'), content);
  console.log('PASS: IDE-local Wi-Fi core exactly matches the current USB source expansion.');
} else {
  writeFileSync(output, content);
  console.log('Prepared IDE-local Wi-Fi core; shared source logic unchanged.');
}
