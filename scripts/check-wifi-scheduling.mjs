import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const wifi=readFileSync('firmware/dloop_wifi_scale/wifi_transport.h','utf8');
const core=readFileSync('firmware/dloop_usb_scale/dloop_usb_scale.ino','utf8');
const reporter=readFileSync('firmware/dloop_usb_scale/diagnostic_reporter.h','utf8');
const settings=readFileSync('firmware/dloop_usb_scale/scale_config.h','utf8');
assert(!wifi.includes('Serial.'),'Only the existing queued writer may write UART');
const formatLiteral=wifi.match(/snprintf_P\(diagnosticBuffer,diagnosticCapacity,PSTR\((".*")\),/)[1];
const format=JSON.parse(formatLiteral);
assert(format.endsWith('\n')&&!format.slice(0,-1).includes('\n'));
const worst=format.replace(/%lu|%u|%d/g,m=>m==='%d'?'-2147483648':'4294967295');
assert(worst.length<1280,'Worst-case Wi-Fi diagnostic must fit existing builder/queue');
assert(wifi.includes('diagnosticSink(formatted>=0&&size_t(formatted)<diagnosticCapacity?diagnosticBuffer:nullptr)'));
const tick=wifi.slice(wifi.indexOf(' void tick('));
assert(tick.indexOf('if(networkPaused)return;')<tick.indexOf('WiFi.disconnect()'));
assert(tick.indexOf('if(networkPaused)return;')<tick.indexOf('probeConnection()'));
assert(tick.indexOf('if(networkPaused)return;')<tick.indexOf('http.POST('));
assert(wifi.includes('nextUpload=millis()+1000;'));
assert(wifi.includes('uint32_t(now-queuedAt)>500'));
assert(settings.includes('SAMPLE_INTERVAL_MS = 100')&&settings.includes('SAMPLE_FRESH_MS = 500'));
for(const condition of ['wifiCalibrationRequested || approximateCalibration.pending()', '(diagnostics.enabled&&diagnostics.full)', 'diagnostics.endPending', 'diagnostics.output.protocol.count || diagnostics.output.diagnostics.count'])assert(core.includes(condition));
for(const field of ['strict_valid=%u','approximate_valid=%u','active_mode=%s','factor_restored=%u'])assert(core.includes(field));
assert(core.indexOf('EEPROM.get(0, saved)')<core.indexOf('wifiScale.begin('));
assert(core.includes('wifiScale.begin(queueWifiDiagnostic,diagnostics.line.text,sizeof(diagnostics.line.text))'));
assert(core.includes('sent < 256 && uint32_t(micros()-started) < 500'));
assert(core.includes('min(unsigned(freeBytes), 256U-sent)'));
assert(core.includes('if (!written) break;'));
for(const field of ['serial_protocol_lost=','serial_diagnostic_lost=','serial_format_lost=','net_block_ms=','net_block_max_ms='])assert(wifi.includes(field));
assert(reporter.includes('++diagnosticLost')&&reporter.includes('++formatLost')&&reporter.includes('OUTPUT_OVERFLOW'));
for(const forbidden of ['setInsecure(', 'EEPROM.put(', 'EEPROM.commit(', 'factor ='])assert(!wifi.includes(forbidden));
console.log('PASS: queued complete Wi-Fi lines fit worst-case bounds; UART budget/backpressure; calibration/trace network barrier; startup flags; upload/freshness cadence and overflow-source reporting.');
