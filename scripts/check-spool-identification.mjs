import assert from 'node:assert/strict';
import './test-typescript-loader.mjs';
const {resolveSpool,tagUrl,writePhoneTag}=await import('../lib/spool-identification.ts');
const token='a'.repeat(48),replacement='b'.repeat(48);
const spool={id:'one',code:'PLA_WHITE_01',nfc:'04A1B2C3D4E5F6',tagToken:token,status:'active'};
for(const id of [{kind:'code',value:' pla_white_01 '},{kind:'hardware-uid',value:'04:a1:b2:c3:d4:e5:f6'},{kind:'tag-token',value:token}])assert.equal(resolveSpool([spool],id)?.id,'one');
assert.equal(resolveSpool([spool],{kind:'code',value:'unknown'}),null);
assert.equal(resolveSpool([spool,{...spool,id:'duplicate'}],{kind:'code',value:spool.code}),null);
assert.equal(resolveSpool([{...spool,status:'archived'}],{kind:'tag-token',value:token}),null);
assert.equal(resolveSpool([{...spool,tagToken:replacement}],{kind:'tag-token',value:token}),null);
assert.equal(resolveSpool([{...spool,tagToken:replacement}],{kind:'tag-token',value:replacement}).id,'one');
assert.equal(tagUrl(null,token),null);
for(const origin of ['http://studio.invalid','https://localhost','https://127.0.0.1','https://studio.invalid/path','https://user:password@studio.invalid'])assert.equal(tagUrl(origin,token),null);
assert.equal(tagUrl('https://studio.example.invalid',token),`https://studio.example.invalid/#/spool/${token}`);
assert(!tagUrl('https://studio.example.invalid',token).includes('982'));
globalThis.window={isSecureContext:true,top:null};globalThis.location={protocol:'http:'};window.top=window;window.location=location;
await assert.rejects(()=>writePhoneTag(`https://studio.example.invalid/#/spool/${token}`));
location.protocol='https:';let records;
window.NDEFReader=class{async write(data){records=data.records;}};
await writePhoneTag(`https://studio.example.invalid/#/spool/${token}`);
assert.deepEqual(records,[{recordType:'url',data:`https://studio.example.invalid/#/spool/${token}`}]);
console.log('PASS: code/phone-token/hardware-UID resolve the same existing spool; unknown/duplicate/archived fail closed; replacement invalidates old token; URL contains identifier only; HTTPS-gated phone writer (mock, no physical NFC).');
