import assert from 'node:assert/strict';
import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
import './test-typescript-loader.mjs';
const root=resolve('.').replaceAll('\\','/');
mkdirSync('work/single-point-tests',{recursive:true});
writeFileSync('work/single-point-tests/tests.cpp',`#include "${root}/firmware/dloop_usb_scale/approximate_calibration.h"\n#include "${root}/firmware/dloop_wifi_scale/single_point_calibration.h"\n`);
const compiler=process.env.DLOOP_CXX||`${process.env.LOCALAPPDATA}/Arduino15/packages/esp8266/tools/xtensa-lx106-elf-gcc/3.1.0-gcc10.3-e5f9fec/bin/xtensa-lx106-elf-g++.exe`;
const result=spawnSync(compiler,['-std=c++17','-fconstexpr-ops-limit=100000000','-fsyntax-only','work/single-point-tests/tests.cpp'],{encoding:'utf8'});
assert.equal(result.status,0,result.stderr||result.error?.message);
const core=readFileSync('firmware/dloop_usb_scale/dloop_usb_scale.ino','utf8');
const module=readFileSync('firmware/dloop_wifi_scale/single_point_calibration.h','utf8');
assert(module.includes('EEPROM_ADDRESS=80, EEPROM_BYTES=128'));
assert(module.includes('long* raw;uint32_t* times;double* scratch;'));
assert(core.includes('singlePointCalibration{approximateCalibration.raw,approximateCalibration.times,approximateCalibration.scratch}'));
const command=core.slice(core.indexOf('bool singlePointCommand('),core.indexOf('\nvoid processCommand('));
assert.equal((command.match(/EEPROM\.put\(/g)||[]).length,1);
assert(command.includes('EEPROM.put(SinglePointCalibration::EEPROM_ADDRESS,record)'));
assert(command.indexOf('canAccept(now)')<command.indexOf('EEPROM.put('));
assert(command.indexOf('EEPROM.commit()')<command.indexOf('singlePointSaved=record;singlePointInstalled=true'));
assert(!command.includes('invalidateSavedRecord('));
assert(core.includes('if(eepromReady)EEPROM.get(SinglePointCalibration::EEPROM_ADDRESS,singlePointSaved)'));
assert(core.includes('approximateCalibration.pending() || singlePointMode ||'));
assert(core.includes('if(singlePointMode){emitSinglePoint(fault);return;}'));
assert(core.indexOf('if(singlePointMode){emitSinglePoint(fault);return;}')<core.indexOf('wifiScale.queue(frame,!calibrated,'));
for(const text of ['reference_based=1','independent_accuracy_verified=0','MODE SINGLE_POINT','SINGLE CAL ','LOG_OUTPUT_LOSS'])assert(core.includes(text));
const {parseScaleFrame,ScaleFrameParser}=await import('../lib/scale/protocol.ts');
const frame={v:1,deviceId:'DLOOP-SCALE-01',seq:1,grossG:1802,stable:true,calibrated:true,mode:'SINGLE_POINT'};
assert.equal(parseScaleFrame(JSON.stringify(frame)).kind,'invalid','Current dashboard must reject unsupported provenance');
const parser=new ScaleFrameParser();
assert.deepEqual(parser.push(new TextEncoder().encode('#DEBUG SINGLE_POINT mode=SINGLE_POINT reference_based=1 independent_accuracy_verified=0 gross_g=1802\n')),[]);
assert.equal(parser.stats.debugLines,1);
console.log('PASS: compiled SINGLE_POINT state/numerical/fault/record/restoration assertions; shared-buffer exclusivity, separate EEPROM slot and explicit commit; network/API isolation; dashboard rejects unsupported measurement provenance.');
