const core=readFileSync('firmware/dloop_usb_scale/dloop_usb_scale.ino','utf8');
const helper=readFileSync('firmware/dloop_wifi_scale/single_point_acquisition.h','utf8');
const rules=readFileSync('firmware/dloop_wifi_scale/single_point_calibration.h','utf8');
