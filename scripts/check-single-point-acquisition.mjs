assert(scheduling.includes('if(singlePointMode)pollDue=SinglePointAcquisition::due(now,lastPoll,lastSample,rawObserved);'));
assert(scheduling.includes('else\n#endif\n  pollDue=uint32_t(now-lastPoll)>=SAMPLE_INTERVAL_MS;'));
